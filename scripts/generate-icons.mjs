/**
 * generate-icons — the home-screen PNGs from `public/touch-icons/apple-touch-icon-dark.svg` (the lettering,
 * hand-placed in the KOL 24-box), the share image from `public/svg/wordmark.svg`.
 * fxr's shape (its plans 11 + 25): white on #121215, the mark in the middle 60% of a square;
 * the maskable icon keeps it inside the safe circle (middle 50%); the OG image is the
 * wordmark at banner proportion. Touch either SVG, run this, commit all of it.
 *
 *   pnpm icons
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import sharp from 'sharp'

const GROUND = '#121215'
const INK = '#FFFFFF'
const SRC = 'public/touch-icons/apple-touch-icon-dark.svg'
const icon = readFileSync(SRC, 'utf8')
/* the lettering = the inner of the one placed <g> in the source — what sits in the middle 60% */
const m = icon.match(/<g transform="translate\([^)]*\) scale\([^)]*\)" style="color:[^"]*">([\s\S]*?)<\/g>\s*<\/svg>/)
if (!m) throw new Error(`${SRC}: no placed lettering group`)
const mark = m[1]

const square = (scale, note) => `<svg width="180" height="180" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">
<!-- Mirror app icon, dark: ${note} -->
<rect width="24" height="24" fill="${GROUND}"/>
<g transform="translate(${((1 - scale) * 12).toFixed(2)} ${((1 - scale) * 12).toFixed(2)}) scale(${scale})" style="color:${INK}">${mark}</g>
</svg>`
/* the share image is the WORDMARK (2026-10-22, the user's pick: widedark — MIRROR is the name), public/svg/wordmark.svg
   across the middle of the same ground; the small sizes above keep the mark. The mark-only banner is in _tmp/2026-10-22-og-before/. */
const wm = readFileSync('public/svg/wordmark.svg', 'utf8')
const vb = wm.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number)
const wmInner = wm.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '')
const bw = 840, bh = bw * vb[3] / vb[2]
const banner = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<!-- Mirror share image: the wordmark (public/svg/wordmark.svg), white on ${GROUND}. Generated by pnpm icons. -->
<rect width="1200" height="630" fill="${GROUND}"/>
<svg x="${(600 - bw / 2).toFixed(1)}" y="${(315 - bh / 2).toFixed(1)}" width="${bw}" height="${bh.toFixed(1)}" viewBox="${vb.join(' ')}" style="color:${INK}">${wmInner}</svg>
</svg>`

mkdirSync('public/og', { recursive: true })
const maskable = square(0.5, 'maskable — the lettering in the middle 50%, inside the safe circle')
writeFileSync('public/og/mirror.svg', banner)
const png = (svg, size, out) => sharp(Buffer.from(svg), { density: 300 }).resize(size, size).png().toFile(out)
await png(icon, 180, 'public/touch-icons/apple-touch-icon-dark.png')
await png(icon, 192, 'public/touch-icons/icon-192.png')
await png(icon, 512, 'public/touch-icons/icon-512.png')
await png(maskable, 512, 'public/touch-icons/icon-512-maskable.png')
await sharp(Buffer.from(banner), { density: 150 }).resize(1200, 630).png().toFile('public/og/mirror.png')
console.log('icons from touch-icons/apple-touch-icon-dark.svg: 180/192/512 + maskable 512 · og 1200×630 from svg/wordmark.svg')
